def _setup_stdio() -> None:
    """尽力把输出流切到 UTF-8，避免 Windows 控制台中文/表情乱码。"""
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            try:
                stream.reconfigure(encoding="utf-8", errors="replace")
            except (ValueError, OSError):
                pass


def normalize(item: str) -> str:
    """去首尾空白，英文转小写，并把别称归一到经典条目名。"""
    item = item.strip()
    key = item.lower() if item.isascii() else item
    return ALIASES.get(key, key)


def interpret(item: str, rng: random.Random) -> str:
    """对一个梦境事物生成解读块。"""
    entry = DREAMS.get(normalize(item))
    if entry is not None:
        text = rng.choice(entry)
        source = "经典条目"
    else:
        text = rng.choice(GENERIC).format(x=item)
        source = "民间偏方"
    luck = rng.randint(1, 100)
    yi = rng.choice(YI)
    ji = rng.choice(JI)
    return "\n".join([
        f"🔮 所梦之物：{item}（{source}）",
        f"  解梦：{text}",
        f"  吉凶指数：{luck} / 100",
        f"  宜：{yi}",
        f"  忌：{ji}",
    ])


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="dream-dict.py",
        description="周公解梦玩具 —— 输入梦到的事物，输出随机趣味梦境解析。",
    )
    parser.add_argument("items", nargs="*", metavar="事物",
                        help="梦里的事物，可给多个，如：蛇 掉牙")
    parser.add_argument("--seed", type=int, default=None,
                        help="随机种子，固定后结果可复现")
    parser.add_argument("--list", action="store_true",
                        help="列出收录的经典条目")
    return parser


def main(argv: list[str] | None = None) -> int:
    _setup_stdio()
    parser = build_parser()
    args = parser.parse_args(argv)
    if args.list:
        print("📖 收录的经典条目：" + "、".join(DREAMS.keys()))
        print("其余任意词走'民间偏方'模板，随便输什么都能解。")
        return 0
    if not args.items:
        parser.error("至少输入一个梦里的事物，例如：python dream-dict.py 蛇")
    rng = random.Random(args.seed)
    print("🔮 周公解梦（玩具版）")
    for item in args.items:
        print(interpret(item, rng))
        print()
    print("（解梦纯属娱乐，不构成医疗、投资或人生建议。）")
    return 0


if __name__ == "__main__":
    sys.exit(main())
