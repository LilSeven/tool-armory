# 句读/引号/括号等，其后视为句首位置
_SENT_BOUNDARY = set("。！？；：，、…—·\"'‘’“”「」『』（）()【】《》<>\n\r\t \u3000")


def char_rule(ch: str, prev: str, nxt: str) -> str:
    """单字级上下文规则。返回替换字符，或 None 表示交给单字表。"""
    if ch == "余":
        # 句首（文本开头或标点之后）多为第一人称代词「余」，姓氏同理；
        # 其余位置默认按「剩餘」义转为「餘」。
        if prev == "" or prev in _SENT_BOUNDARY or prev == "姓":
            return "余"
        return "餘"
    return None


def convert(text: str, words=None, chars=None, rule=None) -> str:
    """简→繁核心：最长词优先 → 上下文规则 → 单字映射 → 原样保留。"""
    words = WORDS if words is None else words
    chars = CHARS if chars is None else chars
    rule = char_rule if rule is None else rule
    order = sorted(words, key=len, reverse=True)
    maxlen = len(order[0]) if order else 0
    out = []
    i, n = 0, len(text)
    while i < n:
        hit = None
        for length in range(min(maxlen, n - i), 1, -1):
            rep = words.get(text[i:i + length])
            if rep is not None:
                hit = rep
                i += length
                break
        if hit is None:
            ch = text[i]
            prev = text[i - 1] if i else ""
            nxt = text[i + 1] if i + 1 < n else ""
            rep = rule(ch, prev, nxt) if rule else None
            out.append(rep if rep else chars.get(ch, ch))
            i += 1
        else:
            out.append(hit)
    return "".join(out)


def build_argparser(desc: str) -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description=desc)
    p.add_argument("-t", "--text", help="直接转换该段文本")
    p.add_argument("-i", "--input", help="从文件读取（默认按 --encoding 解码）")
    p.add_argument("-o", "--output", help="写出文件（默认打印到 stdout）")
    p.add_argument("--encoding", default="utf-8-sig",
                   help="输入文件编码，默认 utf-8-sig（自动去 BOM）")
    return p


def read_source(args) -> str:
    if args.text is not None:
        return args.text
    if args.input:
        with open(args.input, "r", encoding=args.encoding, errors="replace") as f:
            return f.read()
    if not sys.stdin.isatty():
        return sys.stdin.read()
    raise SystemExit("未提供输入：请用 --text、--input 或管道传入文本")


def write_result(args, text: str) -> None:
    if args.output:
        with open(args.output, "w", encoding="utf-8") as f:
            f.write(text)
    else:
        sys.stdout.write(text)
        if not text.endswith("\n"):
            sys.stdout.write("\n")


def main(argv=None) -> int:
    # Windows 控制台/管道下把标准流统一为 UTF-8，避免 GBK 编码报错
    for stream in (sys.stdout, sys.stdin):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8", errors="replace")
    args = build_argparser("简体转繁体转换器（最长词优先，避免「头发→頭發」类错转）").parse_args(argv)
    write_result(args, convert(read_source(args)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
