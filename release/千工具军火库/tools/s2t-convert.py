def _pairs(s: str) -> dict:
    """解析空格分隔的成对字符（简、繁各一）。"""
    d = {}
    for tok in s.split():
        if len(tok) != 2:
            raise ValueError("单字表出现非成对条目: %r" % tok)
        d[tok[0]] = tok[1]
    return d


def _worddict(s: str) -> dict:
    """解析「简=繁」逐行词表，忽略空行与 # 注释。"""
    d = {}
    for line in s.strip().splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        k, sep, v = line.partition("=")
        if not sep or not k or not v:
            raise ValueError("词表行格式错误: %r" % line)
        d[k] = v
    return d


